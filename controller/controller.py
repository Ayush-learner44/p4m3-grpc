"""
P4M3 Controller — Pure gRPC Implementation
Algorithm 3: Machine Learning Detection Module

Flow:
  1. Connect to all switches via P4Runtime/gRPC
  2. Install L2 forwarding rules (MAC -> port)
  3. Enable digest on leaf1 and leaf3 (cpu_digest_t, receiver_id=1)
  4. Block on gRPC stream — switch pushes digest messages the instant SYN fires
  5. On WINDOW_SIZE packets from same MAC: classify with ensemble, block if attack
"""

